#!/usr/bin/env python3
"""Build FR (A1–B2) and full IT packs from EN + sentence overrides."""
from __future__ import annotations

import json
from pathlib import Path

from seeds_common import Q1, Q2, mk, sp, tit, voc
from seeds_en import PACK as EN_PACK
from seeds_en_rest import A1, A2, B1, B2
from seeds_fr import PACK as FR_A0

EN_PACK = {**EN_PACK, "A1": A1, "A2": A2, "B1": B1, "B2": B2}

DATA = Path(__file__).resolve().parent / "locale_overrides.json"


def load_overrides():
    return json.loads(DATA.read_text(encoding="utf-8"))


def localize_story(en_tuple, lang, ov):
    cat, kind, em, title, _s, pl, _en, v_en, q1, q2 = en_tuple
    s = sp(ov["s"])
    en_tr = sp(ov.get("en", "|".join(_en if isinstance(_en, list) else _en)))
    if isinstance(_en, list):
        en_tr = _en
    else:
        en_tr = list(_en)
    voc_rows = []
    for item in ov.get("vocab", []):
        w, p, e, pos = item
        voc_rows.append((w, p, e, pos))
    if not voc_rows:
        voc_rows = [(x["word"], x["gloss"]["pl"], x["gloss"]["en"], x["pos"]) for x in v_en]
    new_title = dict(title)
    if lang == "fr" and "fr" in ov:
        new_title["fr"] = ov["fr"]
    if lang == "it" and "it" in ov:
        new_title["it"] = ov["it"]
    return mk(cat, kind, em, new_title, s, pl, en_tr, voc(*voc_rows), q1, q2)


def build_it(ov):
    pack = {}
    for lv in ("A0", "A1", "A2", "B1", "B2"):
        pack[lv] = []
        for i, st in enumerate(EN_PACK[lv], start=1):
            key = f"it-{lv.lower()}-{i:02d}"
            pack[lv].append(localize_story(st, "it", ov[key]))
    return pack


def build_fr_rest(ov):
    pack = {"A0": FR_A0["A0"]}
    for lv in ("A1", "A2", "B1", "B2"):
        pack[lv] = []
        for i, st in enumerate(EN_PACK[lv], start=1):
            key = f"fr-{lv.lower()}-{i:02d}"
            pack[lv].append(localize_story(st, "fr", ov[key]))
    return pack


def write_pack(name, pack):
    var = {"fr": "FR_PACK", "it": "IT_PACK"}[name]
    out = Path(__file__).resolve().parent / f"story_packs_{name}.py"
    lines = [f"# Auto-generated by localize_packs.py", f"{var} = {{"]
    for lv in ("A0", "A1", "A2", "B1", "B2"):
        lines.append(f'    "{lv}": [')
        for st in pack[lv]:
            lines.append(f"        {repr(st)},")
        lines.append("    ],")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Wrote", out)


def write_seeds_it_py(pack):
    path = Path(__file__).resolve().parent / "seeds_it.py"
    path.write_text(
        "from localize_packs import EN_PACK  # noqa: F401\n"
        "from seeds_fr import PACK  # placeholder\n"
        "PACK = " + repr(pack) + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    ov = load_overrides()
    fr = build_fr_rest(ov)
    it = build_it(ov)
    write_pack("fr", fr)
    write_pack("it", it)
    # also patch seeds modules for write_seeds fallback
    Path(__file__).resolve().parent.joinpath("seeds_it.py").write_text(
        "PACK = " + repr(it) + "\n",
        encoding="utf-8",
    )
    Path(__file__).resolve().parent.joinpath("seeds_fr.py").write_text(
        Path(__file__).resolve().parent.joinpath("seeds_fr.py").read_text(encoding="utf-8").split("from seeds_fr_rest")[0]
        + f"PACK = {repr(fr)}\n",
        encoding="utf-8",
    )
