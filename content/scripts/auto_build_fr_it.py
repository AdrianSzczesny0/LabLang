#!/usr/bin/env python3
"""Build FR/IT story packs from EN pack + target sentence lines."""
from __future__ import annotations

import json
from pathlib import Path

from seeds_common import mk
from seeds_en import PACK as EN0
from seeds_en_rest import A1, A2, B1, B2
from seeds_fr import PACK as FR_A0_PACK
from vocab_translations import VOCAB_BY_PL

ROOT = Path(__file__).resolve().parent
EN = {**EN0, "A1": A1, "A2": A2, "B1": B1, "B2": B2}
LEVELS = ("A0", "A1", "A2", "B1", "B2")


def sp(s: str) -> list[str]:
    return [x.strip() for x in s.split("|") if x.strip()]


def load_lines(name: str) -> list[str]:
    return (ROOT / name).read_text(encoding="utf-8").strip().splitlines()


def _align(seq: list, n: int) -> list:
    seq = list(seq)
    if len(seq) >= n:
        return seq[:n]
    while len(seq) < n:
        seq.append(seq[-1] if seq else "")
    return seq


def localize_tuple(en_tuple, target_s: list[str], lang: str):
    cat, kind, em, title, _s, pl, en_tr, voc, q1, q2 = en_tuple
    n = len(target_s)
    pl = _align(pl, n)
    en_tr = _align(en_tr, n)
    title = dict(title)
    if lang == "fr" and "fr" not in title:
        title["fr"] = title.get("en", "")
    if lang == "it" and "it" not in title:
        title["it"] = title.get("en", "")
    loc_voc = []
    for item in voc:
        w = item["word"]
        plk = item["gloss"].get("pl", "")
        if plk in VOCAB_BY_PL:
            row = VOCAB_BY_PL[plk]
            w = row[1] if lang == "fr" else row[3] if lang == "it" else w
        loc_voc.append({**item, "word": w})
    return mk(cat, kind, em, title, target_s, pl, loc_voc, q1, q2, en=en_tr)


def iter_keys():
    idx = 0
    for lv in LEVELS:
        for i in range(1, 11):
            yield lv, i, idx
            idx += 1


def build_it():
    lines = load_lines("it_sentences.txt")
    assert len(lines) == 50, len(lines)
    pack = {lv: [] for lv in LEVELS}
    for (lv, num, idx), line in zip(iter_keys(), lines):
        en_tuple = EN[lv][num - 1]
        pack[lv].append(localize_tuple(en_tuple, sp(line), "it"))
    return pack


def build_fr():
    lines = load_lines("fr_sentences_a1_b2.txt")
    assert len(lines) == 40, len(lines)
    pack = {"A0": FR_A0_PACK["A0"]}
    line_i = 0
    for lv in ("A1", "A2", "B1", "B2"):
        pack[lv] = []
        for num in range(1, 11):
            en_tuple = EN[lv][num - 1]
            pack[lv].append(localize_tuple(en_tuple, sp(lines[line_i]), "fr"))
            line_i += 1
    return pack


def dump(name: str, pack: dict):
    var = {"fr": "FR_PACK", "it": "IT_PACK"}[name]
    out = ROOT / f"story_packs_{name}.py"
    chunks = [f"# Generated by auto_build_fr_it.py", f"{var} = {{"]
    for lv in LEVELS:
        chunks.append(f'    "{lv}": [')
        for st in pack[lv]:
            chunks.append(f"        {repr(st)},")
        chunks.append("    ],")
    chunks.append("}")
    out.write_text("\n".join(chunks) + "\n", encoding="utf-8")
    print("Wrote", out)


if __name__ == "__main__":
    dump("it", build_it())
    dump("fr", build_fr())
